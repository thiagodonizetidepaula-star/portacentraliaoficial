import {writeFile} from 'node:fs/promises';
import gsapPackage from 'gsap/dist/gsap.js';
import {OrthographicCamera, Vector3} from 'three';

const {gsap} = gsapPackage;

const viewport = {width: 640, height: 450};
const camera = new OrthographicCamera(-4.8, 4.8, 3.375, -3.375, 0.1, 50);
camera.position.set(6, 5.2, 7.2);
camera.lookAt(0, 0, 0);
camera.updateMatrixWorld();

const point = (x, y, z) => new Vector3(x, y + z * 0.31, z);
function project(vertex) {
  const p = vertex.project(camera);
  return [(viewport.width * (p.x + 1) / 2).toFixed(1), (viewport.height * (1 - p.y) / 2).toFixed(1)].join(',');
}
function polygon(color, vertices) {
  return '<polygon fill="' + color + '" points="' + vertices.map(project).join(' ') + '"/>';
}
function panel(x, z) {
  const [right, front, depth] = [x + 2.53, z + 3, 0.16];
  const surface = (x, z, w, h, y, color) =>
    polygon(color, [point(x,y,z), point(x+w,y,z), point(x+w,y,z+h), point(x,y,z+h)]);
  let svg = polygon('#567b85', [point(x,0,front),point(right,0,front),point(right,-depth,front),point(x,-depth,front)]);
  svg += polygon('#264656', [point(right,0,z),point(right,0,front),point(right,-depth,front),point(right,-depth,z)]);
  svg += surface(x,z,right-x,front-z,0,'#b1d7d8');
  svg += surface(x+.07,z+.07,right-x-.14,front-z-.14,.01,'#102f59');
  for (let row = 0; row < 6; row++) {
    for (let column = 0; column < 4; column++) {
      const colors = ['#28578a','#3773a0','#235481','#306997'];
      svg += surface(x+.11+column*.585,z+.105+row*.47,.55,.44,.02,colors[(row*3+column)%colors.length]);
    }
  }
  return svg;
}
const model = '<svg viewBox="0 0 640 450" focusable="false" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">' +
  '<ellipse cx="325" cy="321" rx="245" ry="60" fill="#0a3341" opacity=".14"/>' +
  panel(-2.66,-1.5) + panel(.09,-1.5) + '</svg>';

const timing = {vertical: 22, scale: .96};
const lift = gsap.timeline({paused: true})
  .to(timing, {vertical: -5, scale: 1.015, duration: .72, ease: 'power2.out'})
  .to(timing, {vertical: 0, scale: 1, duration: .28, ease: 'sine.inOut'});
const samples = Array.from({length: 11}, (_, index) => {
  lift.progress(index / 10);
  return index * 10 + '%{transform:translateY(' + timing.vertical.toFixed(2) + 'px) scale(' + timing.scale.toFixed(4) + ')}';
});
lift.kill();
const css = '@keyframes prospect-solar-rise{' + samples.join('') + '}';
const payload = JSON.stringify({model, css});
await writeFile(new URL('../studio-premium-art.js', import.meta.url),
  '// Generated by npm run build:premium-art. The preview receives only SVG and CSS.\n' +
  'window.ProspectPremiumArt = Object.freeze(' + payload + ');\n');
